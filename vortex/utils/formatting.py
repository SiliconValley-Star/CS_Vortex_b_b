def generate_markdown_report(findings: list) -> str:
    """
    Generate Markdown report for multiple findings.
    
    Args:
        findings: List of finding dictionaries
        
    Returns:
        Markdown formatted report
    """
    try:
        report = f"""# VORTEX Security Scan Report

**Generated**: {datetime.utcnow().isoformat()}
**Total Findings**: {len(findings)}

## Summary

| Status | Count |
|--------|-------|
"""
        # Add summary statistics
        status_counts = {}
        for finding in findings:
            status = finding.get('status', 'UNKNOWN')
            status_counts[status] = status_counts.get(status, 0) + 1
        
        for status, count in status_counts.items():
            report += f"| {status} | {count} |\n"
        
        report += "\n## Detailed Findings\n\n"
        
        for i, finding in enumerate(findings, 1):
            report += f"""### {i}. {finding.get('type', 'Unknown')} - {finding.get('severity', 'Unknown')}

**URL**: {finding.get('url', 'N/A')}
**Status**: {finding.get('status', 'N/A')}
**Confidence**: {finding.get('confidence', 0.0):.2f}

**Evidence**:
```
{finding.get('evidence', 'No evidence')[:200]}...
```

---

"""
        
        return report
    except Exception as e:
        logger.error(f"Markdown report generation error: {e}")
        return "# Error Generating Report"


def generate_html_report(findings: list) -> str:
    """
    Generate HTML report for multiple findings.
    
    Args:
        findings: List of finding dictionaries
        
    Returns:
        HTML formatted report
    """
    try:
        html = f"""<!DOCTYPE html>
<html>
<head>
    <title>VORTEX Security Report</title>
    <style>
        body {{ font-family: Arial, sans-serif; margin: 20px; }}
        .header {{ background: #333; color: white; padding: 20px; }}
        .finding {{ border: 1px solid #ddd; margin: 10px 0; padding: 15px; }}
        .critical {{ border-left: 4px solid #dc3545; }}
        .high {{ border-left: 4px solid #ffc107; }}
        .medium {{ border-left: 4px solid #17a2b8; }}
        .low {{ border-left: 4px solid #28a745; }}
    </style>
</head>
<body>
    <div class="header">
        <h1>VORTEX Security Scan Report</h1>
        <p>Generated: {datetime.utcnow().isoformat()}</p>
        <p>Total Findings: {len(findings)}</p>
    </div>
    
    <h2>Findings</h2>
"""
        
        for finding in findings:
            severity = finding.get('severity', 'UNKNOWN').lower()
            html += f"""
    <div class="finding {severity}">
        <h3>{finding.get('type', 'Unknown')} - {finding.get('severity', 'Unknown')}</h3>
        <p><strong>URL:</strong> {finding.get('url', 'N/A')}</p>
        <p><strong>Status:</strong> {finding.get('status', 'N/A')}</p>
        <p><strong>Confidence:</strong> {finding.get('confidence', 0.0):.2f}</p>
        <pre>{finding.get('evidence', 'No evidence')[:200]}...</pre>
    </div>
"""
        
        html += """
</body>
</html>
"""
        return html
    except Exception as e:
        logger.error(f"HTML report generation error: {e}")
        return "<html><body><h1>Error Generating Report</h1></body></html>"


