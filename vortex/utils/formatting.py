import logging
from typing import Dict, Any, Optional
from datetime import datetime

logger = logging.getLogger(__name__)


def format_finding_report(finding: Dict[str, Any]) -> str:
    """
    Format finding as detailed report.
    
    Args:
        finding: Finding data dictionary
        
    Returns:
        Formatted report string
    """
    try:
        report = f"""
VORTEX Security Finding Report
{'='*60}

Finding ID: {finding.get('id', 'N/A')}
Status: {finding.get('status', 'N/A')}
Severity: {finding.get('severity', 'N/A')}
Type: {finding.get('type', 'N/A')}

Target Information:
  URL: {finding.get('url', 'N/A')}
  Parameter: {finding.get('parameter', 'N/A')}
  Method: {finding.get('method', 'GET')}

Evidence:
{finding.get('evidence', 'No evidence available')}

Confidence Scores:
  Heuristic: {finding.get('heuristic_score', 0.0):.2f}
  System Verification: {finding.get('system_confidence', 0.0):.2f}
  AI Confidence: {finding.get('ai_confidence', 0.0):.2f}

Timestamp: {finding.get('created_at', datetime.utcnow().isoformat())}
{'='*60}
"""
        return report.strip()
    except Exception as e:
        logger.error(f"Report formatting error: {e}")
        return "Error formatting report"


